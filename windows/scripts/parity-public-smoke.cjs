const {_electron}=require('playwright-core');
const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
const project=path.resolve(__dirname,'..');
const profile=path.join(project,'.test-data','parity-public-'+Date.now());
const output=path.join(project,'verification');
const report={date:new Date().toISOString(),scope:'Live anonymous public reads only; no account or forum write requests.',checks:[],errors:[]};
let app;
(async()=>{
  await fs.mkdir(profile,{recursive:true});await fs.mkdir(output,{recursive:true});
  await fs.writeFile(path.join(profile,'preferences.json'),JSON.stringify({settings:{theme:'dark',uiFontSize:16,fontSize:18,nodeSeekPro:false,compact:false,restoreTabs:true,defaultSource:'rss'},workspace:{tabs:[],activeId:null,overviewOpen:true}}));
  const env={...process.env,SEEKDESK_TEST:'1',SEEKDESK_USER_DATA:profile};delete env.ELECTRON_RUN_AS_NODE;delete env.SEEKDESK_DEV_URL;
  app=await _electron.launch({executablePath:require('electron'),args:[project],env});
  const page=await app.firstWindow();page.on('pageerror',error=>report.errors.push(error.message));
  await page.locator('.workspace').waitFor();
  const listing=await page.evaluate(()=>window.seekdesk.listPosts({}));
  assert.equal(listing.source,'rss');assert.ok(listing.posts.length>0);
  report.checks.push({name:'Live public RSS',count:listing.posts.length,source:listing.source});
  await page.getByTestId('post-row').first().waitFor({timeout:40000});
  await page.getByTestId('post-row').first().click();
  await page.getByTestId('reader-content').first().waitFor({timeout:30000});
  assert.ok((await page.locator('.reading-panel').innerText()).includes('RSS'));
  await page.screenshot({path:path.join(output,'parity-public-reading.png')});
  report.checks.push({name:'Live public thread summary explicitly marked partial',title:listing.posts[0].title});
  const ranking=await page.evaluate(()=>window.seekdesk.getHotRanking('realtime'));
  assert.ok(ranking.items.length>0);report.checks.push({name:'Live ranking',count:ranking.items.length});
  const statements=await page.evaluate(()=>window.seekdesk.queryRulings(0,'cshaizhihao'));
  assert.ok(Array.isArray(statements.records));report.checks.push({name:'Live moderation records',count:statements.records.length});
  const rates=await page.evaluate(()=>window.seekdesk.getExchangeRates('USD'));
  assert.ok(rates.rates.CNY>0);report.checks.push({name:'Live exchange rates',source:rates.source,quote:rates.rates.CNY,date:rates.fetchedAt});
  await page.getByRole('button',{name:'扩展中心',exact:true}).click();await page.getByRole('heading',{name:'扩展中心',exact:true}).waitFor();
  await page.locator('.extensions-page').getByRole('button',{name:/^全部/}).click();
  assert.equal(await page.locator('.extension-card').count(),8);
  await page.screenshot({path:path.join(output,'parity-public-extensions.png')});
  report.checks.push({name:'All eight original extensions rendered'});
  assert.deepEqual(report.errors,[]);
  console.log(JSON.stringify(report,null,2));
})().catch(error=>{report.failure=error.stack;console.error(error);process.exitCode=1;}).finally(async()=>{await fs.writeFile(path.join(output,'parity-public-report.json'),JSON.stringify(report,null,2));if(app)await app.close();});
